//============================================================================
// 运行时状态
//============================================================================
static uint8_t  volt_idx;
static uint8_t  curr_idx[4];       // 4个电机各自电流索引
static bool     moving[4];         // 运动状态
static float    curr_ema[4];       // 电流EMA平滑值
static float    temp_val[4];       // 温度浮点值 (慢漂)
static float    temp_target[4];    // 温度漂移目标
static uint16_t temp_timer[4];     // 温度漂移计时器

void sim_init(void) {
    volt_idx = rand() & 0xFF;
    for (int i = 0; i < 4; i++) {
        curr_idx[i] = (rand() + i * 67) & 0xFF;
        moving[i] = false;
        curr_ema[i] = CURRENT_IDLE[curr_idx[i]];
        temp_val[i] = 33.0f + (float)(rand() % 500) / 100.0f;  // 33-38°C 初始
        temp_target[i] = temp_val[i];
        temp_timer[i] = (rand() % 200) + 100;  // 10-30秒后换方向
    }
}

void sim_set_moving(int motor_idx, bool mv) {
    if (motor_idx < 0 || motor_idx > 3) return;
    moving[motor_idx] = mv;
}

void sim_tick(void) {
    volt_idx++;

    for (int i = 0; i < 4; i++) {
        curr_idx[i]++;

        // 电流目标
        uint16_t target;
        if (moving[i]) {
            switch (i) {
                case 0: target = CURRENT_M1[curr_idx[i]]; break;
                case 1: target = CURRENT_M2[curr_idx[i]]; break;
                case 2: target = CURRENT_M3[curr_idx[i]]; break;
                case 3: target = CURRENT_M4[curr_idx[i]]; break;
                default: target = 0;
            }
        } else {
            target = CURRENT_IDLE[curr_idx[i]];
        }

        // EMA 平滑: alpha=0.12, ~20步(~2秒)达稳态
        curr_ema[i] = curr_ema[i] * 0.88f + (float)target * 0.12f;

        // 温度漂移: 每次tick只变0.003°C, 方向每10-30秒换一次
        if (--temp_timer[i] == 0) {
            temp_timer[i] = ((rand() % 200) + 100);  // 10-30秒
            float delta = ((float)(rand() % 100) - 50.0f) / 100.0f * 2.0f;  // ±1°C
            temp_target[i] = temp_val[i] + delta;
            if (temp_target[i] < 30.0f) temp_target[i] = 30.0f + (float)(rand()%100)/100.0f;
            if (temp_target[i] > 40.0f) temp_target[i] = 40.0f - (float)(rand()%100)/100.0f;
        }
        // 向目标缓慢靠近
        float diff = temp_target[i] - temp_val[i];
        if (fabsf(diff) > 0.001f) {
            float step = diff * 0.003f;  // 每次靠近0.3%的差距 → 极慢
            if (fabsf(step) > 0.02f) step = (step > 0 ? 0.02f : -0.02f);  // 限步进
            temp_val[i] += step;
        }
        // 运动中稍微偏热
        if (moving[i] && temp_val[i] < 39.0f) temp_val[i] += 0.001f;
        // 钳制
        if (temp_val[i] < 30.0f) temp_val[i] = 30.0f;
        if (temp_val[i] > 40.0f) temp_val[i] = 40.0f;
    }
}

uint16_t sim_voltage_mv(void) { return VOLT_LUT[volt_idx]; }

uint16_t sim_current_ma(int motor_idx) {
    if (motor_idx < 0 || motor_idx > 3) return 0;
    return (uint16_t)(curr_ema[motor_idx] + 0.5f);
}

float sim_temperature_c(int motor_idx) {
    if (motor_idx < 0 || motor_idx > 3) return 35.0f;
    return temp_val[motor_idx];
}
